-- Promoções (TGFDES) em vigor hoje, já abertas por produto ativo. Três formas de cadastro:
-- direto no produto (CODPROD preenchido); por grupo de desconto (CODPROD = 0 e GRUPODESCPROD
-- igual ao TGFPRO.GRUPODESCPROD); ou para todos os produtos (CODPROD = 0 e grupo '***...').
-- Nos campos de grupo o Sankhya grava '***************' para "todos".
-- As datas não têm hora e DTFINAL é o último dia da promoção.
-- Promoções só para um parceiro ou vendedor (ou grupo deles) não mudam o preço de venda geral.
-- Cada parte filtra antes de juntar com a TGFPRO: unir tudo e filtrar depois leva ~1 min.
SELECT X.NUPROMOCAO, X.CODPROD, X.CODTAB, X.CODLOCAL, X.CONTROLE, X.PERCENTUAL, X.VLRDESC, X.VLRVENDA,
       X.DTINICIAL, X.DTFINAL, X.DESCRPROMOCAO
FROM (
    SELECT D.NUPROMOCAO, PRO.CODPROD, D.CODTAB, D.CODLOCAL, D.CONTROLE, D.PERCENTUAL, D.VLRDESC, D.VLRVENDA,
           D.DTINICIAL, D.DTFINAL, D.DESCRPROMOCAO
    FROM TGFDES D
    JOIN TGFPRO PRO ON PRO.CODPROD = D.CODPROD
    WHERE D.CODPROD <> 0 AND PRO.ATIVO = 'S'
      AND D.DTINICIAL <= GETDATE() AND (D.DTFINAL IS NULL OR D.DTFINAL >= CAST(GETDATE() AS DATE))
      AND ISNULL(D.CODPARC, 0) = 0 AND ISNULL(D.GRUPODESCPARC, '*') LIKE '*%'
      AND ISNULL(D.CODVEND, 0) = 0 AND ISNULL(D.GRUPODESCVEND, '*') LIKE '*%'
    UNION ALL
    SELECT D.NUPROMOCAO, PRO.CODPROD, D.CODTAB, D.CODLOCAL, D.CONTROLE, D.PERCENTUAL, D.VLRDESC, D.VLRVENDA,
           D.DTINICIAL, D.DTFINAL, D.DESCRPROMOCAO
    FROM TGFDES D
    JOIN TGFPRO PRO ON PRO.GRUPODESCPROD = D.GRUPODESCPROD
    WHERE D.CODPROD = 0 AND D.GRUPODESCPROD NOT LIKE '*%' AND PRO.ATIVO = 'S'
      AND D.DTINICIAL <= GETDATE() AND (D.DTFINAL IS NULL OR D.DTFINAL >= CAST(GETDATE() AS DATE))
      AND ISNULL(D.CODPARC, 0) = 0 AND ISNULL(D.GRUPODESCPARC, '*') LIKE '*%'
      AND ISNULL(D.CODVEND, 0) = 0 AND ISNULL(D.GRUPODESCVEND, '*') LIKE '*%'
    UNION ALL
    SELECT D.NUPROMOCAO, PRO.CODPROD, D.CODTAB, D.CODLOCAL, D.CONTROLE, D.PERCENTUAL, D.VLRDESC, D.VLRVENDA,
           D.DTINICIAL, D.DTFINAL, D.DESCRPROMOCAO
    FROM TGFDES D
    CROSS JOIN TGFPRO PRO
    WHERE D.CODPROD = 0 AND D.GRUPODESCPROD LIKE '*%' AND PRO.ATIVO = 'S'
      AND D.DTINICIAL <= GETDATE() AND (D.DTFINAL IS NULL OR D.DTFINAL >= CAST(GETDATE() AS DATE))
      AND ISNULL(D.CODPARC, 0) = 0 AND ISNULL(D.GRUPODESCPARC, '*') LIKE '*%'
      AND ISNULL(D.CODVEND, 0) = 0 AND ISNULL(D.GRUPODESCVEND, '*') LIKE '*%'
) X
ORDER BY X.CODPROD, X.NUPROMOCAO
